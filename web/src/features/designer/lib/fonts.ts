export const FONT_GROUPS: readonly FontGroup[] = ["basic", "bold", "script"];

/** CSS font-family of each web font, as generated by next/font (set by DesignProvider). */
let registered: Partial<Record<string, string>> = {};

/** Registers the generated family names of the self-hosted web fonts (id -> CSS font-family). */
export function registerFontFamilies(map: Partial<Record<string, string>> | undefined): void {
  if (map) registered = { ...registered, ...map };
}

const SANS = "Arial, sans-serif";

/** CSS font-family list for a font id (falls back to the id itself, then Arial). */
export function fontCss(id: string): string {
  const own = registered[id];
  if (own) return `${own}, ${SANS}`;
  return `"${id}", ${SANS}`;
}

/** Print weight for a font id (700 when unknown). */
export function fontWeight(id: string): number {
  return (FONT_META as Record<string, FontMeta | undefined>)[id]?.weight ?? 700;
}

/** CSS / canvas font shorthand, e.g. `800 40px '__Montserrat_x', Arial, sans-serif`. */
export function fontShorthand(id: string, sizePx: number): string {
  return `${fontWeight(id)} ${sizePx}px ${fontCss(id)}`;
}
